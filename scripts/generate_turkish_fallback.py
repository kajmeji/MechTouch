"""Generate only the 12 missing Turkish glyphs (Pillow; Windows Arial)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
codes = sorted([199, 286, 304, 214, 350, 220, 231, 287, 305, 246, 351, 252])
lines = ['/* Generated by scripts/generate_turkish_fallback.py. */', '#include <lvgl.h>']
for size in [12,14,16,18,20,22,24,26,28,32,48]:
    font = ImageFont.truetype('C:/Windows/Fonts/arial.ttf', size)
    bits = []
    glyphs = ['{0,0,0,0,0,0}']
    for code in codes:
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        width, height = right-left, bottom-top
        bitmap = Image.new('L', (width, height))
        ImageDraw.Draw(bitmap).text((-left, -top), char, font=font, fill=255, anchor='ls')
        pixels = [(x+8)//17 for x in bitmap.getdata()]
        offset = len(bits)
        if len(pixels)%2: pixels.append(0)
        bits.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
        glyphs.append('{%d,%d,%d,%d,%d,%d}' % (offset, round(font.getlength(char)*16), width, height, left, -bottom))
    name = f'tr_{size}'
    lines += [f'static const uint8_t {name}_bits[] = {{' + ','.join(map(str,bits)) + '};',
        f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{' + ','.join(glyphs) + '};',
        f'static const uint16_t {name}_unicode[] = {{' + ','.join(str(x-codes[0]) for x in codes) + '};',
        f'static const lv_font_fmt_txt_cmap_t {name}_map[] = {{{{.range_start={codes[0]}, .range_length={codes[-1]-codes[0]+1}, .glyph_id_start=1, .unicode_list={name}_unicode, .list_length=12, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};',
        f'static const lv_font_fmt_txt_dsc_t {name}_dsc = {{.glyph_bitmap={name}_bits,.glyph_dsc={name}_glyphs,.cmaps={name}_map,.cmap_num=1,.bpp=4}};',
        f'const lv_font_t {name} = {{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={size+4},.base_line=4,.dsc=&{name}_dsc}};']
(ROOT / 'src/ui/fonts/turkish_fallback.c').write_text('\n'.join(lines)+'\n', encoding='utf-8')
print('Generated 12 Turkish glyphs in 11 font sizes.')
