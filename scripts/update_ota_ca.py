"""Regenerate the OTA-only trust store from Mozilla roots shipped by certifi.

Run manually when reviewing trust-store updates. Normal builds use the checked-in
header and do not download certificates. Never import a server's leaf certificate.
"""
import pathlib
import re
import ssl
import socket
import certifi

NAMES = {
    'DigiCert Global Root G2', 'DigiCert Global Root G3', 'DigiCert Trusted Root G4',
    'USERTrust RSA Certification Authority', 'USERTrust ECC Certification Authority',
    'Sectigo Public Server Authentication Root R46', 'Sectigo Public Server Authentication Root E46',
    'Microsoft RSA Root Certificate Authority 2017', 'Microsoft ECC Root Certificate Authority 2017',
    'ISRG Root X1', 'ISRG Root X2',
}
ROOT = pathlib.Path(__file__).resolve().parents[1]


def main():
    source = pathlib.Path(certifi.where()).read_text(encoding='utf-8')
    certificates = dict(re.findall(r'# Label: "([^"]+)".*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', source, re.S))
    missing = NAMES - certificates.keys()
    if missing:
        raise ValueError(f'Review roots removed from Mozilla trust store: {missing}')
    pem = '\n'.join(certificates[n] for n in sorted(NAMES)) + '\n'
    # Hostname and chain verification must pass before replacing the firmware store.
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.load_verify_locations(cadata=pem)
    for maximum in (ssl.TLSVersion.MAXIMUM_SUPPORTED, ssl.TLSVersion.TLSv1_2):
        context.maximum_version = maximum
        for host in ('github.com', 'release-assets.githubusercontent.com', 'objects.githubusercontent.com'):
            with socket.create_connection((host, 443), timeout=15) as connection:
                with context.wrap_socket(connection, server_hostname=host) as secure:
                    print(f'{host}: certificate chain and hostname verified ({secure.version()})')
    text = '// OTA-only Mozilla CA roots, generated by scripts/update_ota_ca.py\n'
    text += f'// Source: certifi {certifi.__version__}; review and regenerate on CA changes.\n'
    text += '// ' + '\n// '.join(sorted(NAMES)) + '\n#pragma once\n'
    text += 'static const char otaRootCertificates[] = R"OTACA(\n' + pem + ')OTACA";\n'
    (ROOT / 'include/network/ota_ca.h').write_text(text, encoding='ascii')
    print(f'{len(NAMES)} roots, {len(pem)} PEM bytes')


if __name__ == '__main__':
    main()
